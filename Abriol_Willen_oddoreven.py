number = int(input("Enter a number: "))
if number % 2 == 0:
    print("Output: Even")
else:
    print("Output: Odd")

#The program asks the user for a number and checks if it is even or odd.
#It checks by using the modulus operator to determine if the number is divisible by 2.
#If the remainder is 0, it prints "Even", otherwise it prints "Odd".