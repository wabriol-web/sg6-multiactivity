score = int(input("Enter your score: "))
if score >= 90:
    print("Grade: A")
elif score >= 80:
    print("Grade: B")
elif score >= 70:
    print("Grade: C")
else:
    print("Grade: D")

#The program asks the user to input their score to determine their grade.
#It uses if elif statements to check what category is the score in.
#Finally, it prints out the corresponding grade based on the score entered by the user.